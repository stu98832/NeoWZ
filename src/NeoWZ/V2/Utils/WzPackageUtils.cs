using System.Numerics;

namespace NeoWZ.V2.Utils;

public class WzPackageUtils {
    public static readonly byte[] AesKey = new byte[] {
        0x13, 0x00, 0x00, 0x00,
        0x08, 0x00, 0x00, 0x00,
        0x06, 0x00, 0x00, 0x00,
        0xB4, 0x00, 0x00, 0x00,
        0x1B, 0x00, 0x00, 0x00,
        0x0F, 0x00, 0x00, 0x00,
        0x33, 0x00, 0x00, 0x00,
        0x52, 0x00, 0x00, 0x00
    };

    public static uint GetOffsetKey(uint cur, int hash) {
        uint key = (uint)(((~cur) * hash) - 0x581C3F6D);
        return BitOperations.RotateLeft(key, (byte)(key & 0x1F));
    }
}